from __future__ import annotations

import argparse
import asyncio
import json
import statistics
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
BACKEND_ROOT = PROJECT_ROOT / "backend"
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from app.core.config import get_settings
from app.core.paths import DATA_ROOT
from app.speech.profile import VoiceSynthesisOptions
from app.speech.prosody import ProsodyProcessor
from app.speech.stt import FasterWhisperSTT
from app.speech.tts import tts_provider_catalog
from app.voice_hunter.audio import analyze_audio, normalize_candidate_audio
from app.voice_hunter.models import LatencyMetrics, STTValidation
from app.voice_hunter.service import BENCHMARK_PHRASES, VoiceHunterService, utc_now


def merge_benchmark_files(output_root: Path) -> dict[str, dict]:
    merged: dict[str, dict] = {}
    for path in output_root.glob("*/benchmark.json"):
        try:
            merged[path.parent.name] = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
    (output_root / "summary.json").write_text(json.dumps(merged, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return merged


async def benchmark(args: argparse.Namespace) -> int:
    settings = get_settings()
    providers = tts_provider_catalog(
        settings.tts_model_path, settings.tts_voices_path, settings.tts_voice,
        settings.chatterbox_python, settings.chatterbox_device, settings.chatterbox_reference,
        settings.chatterbox_model_id, settings.chatterbox_ptbr_model_id,
        settings.chatterbox_resident, settings.chatterbox_timeout_seconds,
        settings.edge_tts_enabled, settings.edge_tts_default_locale,
        settings.edge_tts_gender_filter, settings.edge_tts_timeout_seconds,
    )
    stt = FasterWhisperSTT(settings.stt_model, settings.stt_device, settings.stt_compute_type, settings.stt_language)
    hunter = VoiceHunterService(stt=stt, tts_catalog=providers)
    if args.seed_omnivoice:
        await hunter.register_sample(
            "omnivoice-brpt-calm-design", args.seed_omnivoice,
            "locally generated by Apache-2.0 OmniVoice voice design; no reference audio",
        )

    requested = [item.strip() for item in args.candidates.split(",") if item.strip()]
    phrases = list(BENCHMARK_PHRASES) if args.phrases == "all" else [item.strip() for item in args.phrases.split(",") if item.strip()]
    output_root = DATA_ROOT / "voice-benchmarks" / "voice-hunter"
    if args.merge_only:
        print(json.dumps({"merged": sorted(merge_benchmark_files(output_root))}, ensure_ascii=False))
        return 0
    results: dict[str, dict] = {}
    for candidate_id in requested:
        candidate = hunter.get_candidate(candidate_id)
        provider_name = "chatterbox_multilingual_v3" if candidate.reference_allowed else candidate.provider
        provider = next((item for item in providers if item.name == provider_name), None)
        if provider is None:
            results[candidate_id] = {"error": "provider not configured"}
            continue
        health_started = time.perf_counter()
        if not await provider.health():
            results[candidate_id] = {"error": "provider unavailable"}
            continue
        cold_ms = round((time.perf_counter() - health_started) * 1000, 1)
        candidate_dir = output_root / candidate_id
        candidate_dir.mkdir(parents=True, exist_ok=True)
        timings: list[float] = []
        entries: dict[str, dict] = {}
        for phrase in phrases:
            text = BENCHMARK_PHRASES[phrase]
            prepared = ProsodyProcessor().prepare(text, provider=provider.name)
            options = VoiceSynthesisOptions(provider=provider.name, voice=candidate.provider_voice or "default")
            started = time.perf_counter()
            if candidate.reference_allowed:
                raw = await provider.synthesize_with_reference(prepared.speech_text, hunter.sample_path(candidate_id), "neutral", options)
            else:
                raw = await provider.synthesize(prepared.speech_text, "neutral", options)
            elapsed_ms = round((time.perf_counter() - started) * 1000, 1)
            timings.append(elapsed_ms)
            output = candidate_dir / f"{phrase}.wav"
            metrics = await asyncio.to_thread(normalize_candidate_audio, raw, output)
            validation = None
            if not args.skip_stt:
                try:
                    transcript = await stt.transcribe(output)
                    validation = {
                        "language": transcript.language, "confidence": transcript.language_probability,
                        "transcription": transcript.text, "duration_s": transcript.duration_seconds,
                    }
                except Exception as exc:
                    validation = {"error": type(exc).__name__}
            entries[phrase] = {
                "display_text": text, "speech_text": prepared.speech_text,
                "synthesis_ms": elapsed_ms, "audio": str(output.relative_to(PROJECT_ROOT)).replace("\\", "/"),
                "analysis": metrics.model_dump(mode="json"), "stt": validation,
                "real_time_factor": round(elapsed_ms / max(metrics.duration_s * 1000, 1), 3),
            }
            if phrase == "casual" and not candidate.reference_allowed:
                await hunter.register_sample(candidate_id, output, f"locally synthesized by {provider.name}")
        warm = statistics.median(timings[1:] or timings)
        last = entries[phrases[-1]]
        candidate.latency = LatencyMetrics(
            cold_start_ms=cold_ms, warm_generation_ms=round(warm, 1),
            total_synthesis_ms=round(sum(timings), 1),
            audio_duration_ms=round(sum(item["analysis"]["duration_s"] for item in entries.values()) * 1000, 1),
            real_time_factor=round(sum(timings) / max(sum(item["analysis"]["duration_s"] for item in entries.values()) * 1000, 1), 3),
            measured_at=utc_now(),
        )
        candidate.benchmark = {"phrases": entries, "pronunciation_engine": "V3.2", "resident_worker": bool(getattr(provider, "resident", False))}
        if candidate.reference_allowed:
            candidate.analysis = analyze_audio(hunter.sample_path(candidate_id))
            if not args.skip_stt:
                sample_transcript = await stt.transcribe(hunter.sample_path(candidate_id))
                candidate.stt = STTValidation(
                    language=sample_transcript.language, confidence=sample_transcript.language_probability,
                    transcription=sample_transcript.text, duration_s=sample_transcript.duration_seconds,
                )
        elif entries.get("casual", {}).get("stt") and "error" not in entries["casual"]["stt"]:
            value = entries["casual"]["stt"]
            candidate.stt = STTValidation.model_validate(value)
        results[candidate_id] = {
            "provider": provider.name, "cold_start_ms": cold_ms, "warm_generation_ms": round(warm, 1),
            "total_synthesis_ms": round(sum(timings), 1), "phrases": entries,
            "last_audio_duration_s": last["analysis"]["duration_s"],
        }
        (candidate_dir / "benchmark.json").write_text(json.dumps(results[candidate_id], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        await hunter._persist()
        print(json.dumps({candidate_id: results[candidate_id]}, ensure_ascii=False), flush=True)
    merge_benchmark_files(output_root)
    for provider in providers:
        if hasattr(provider, "_stop_server"):
            await provider._stop_server()
    print(json.dumps({"downloaded_bytes": hunter._downloaded_bytes(), "budget_bytes": hunter.budget}, ensure_ascii=False))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Real Voice Hunter benchmark; no mocks or automatic profile selection.")
    parser.add_argument("--candidates", default="kokoro-pf-dora,chatterbox-multilingual-default,omnivoice-brpt-calm-design")
    parser.add_argument("--phrases", default="all")
    parser.add_argument("--seed-omnivoice", type=Path)
    parser.add_argument("--skip-stt", action="store_true")
    parser.add_argument("--merge-only", action="store_true")
    return asyncio.run(benchmark(parser.parse_args()))


if __name__ == "__main__":
    raise SystemExit(main())
